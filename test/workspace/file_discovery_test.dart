import 'dart:io';

import 'package:ciach/src/workspace/file_discovery.dart';
import 'package:path/path.dart' as p;
import 'package:test/test.dart';

void main() {
  late Directory tempDir;

  setUp(() {
    tempDir = .systemTemp.createTempSync('ciach_discovery_test_');
  });

  tearDown(() {
    tempDir.deleteSync(recursive: true);
  });

  void write(String relativePath, String content) {
    File(p.join(tempDir.path, p.joinAll(p.posix.split(relativePath))))
      ..createSync(recursive: true)
      ..writeAsStringSync(content);
  }

  /// Relative POSIX paths of [absolutePaths], for order-independent asserts.
  Set<String> rel(List<String> absolutePaths) => {
    for (final path in absolutePaths)
      p.split(p.relative(path, from: tempDir.path)).join('/'),
  };

  test(
    'a file generated by its name is listed as generated whichever globs select it, and the rest by the globs',
    () {
      write('lib/model.dart', 'class Model {}');
      write('lib/other.dart', 'class Other {}');
      write('lib/model.g.dart', '// generated\nclass ModelGen {}');

      final result = dartFilesByPath(
        .new(rootPath: tempDir.path, includeGlobs: const ['lib/model.dart']),
      );

      expect(rel(result.selected), {'lib/model.dart'});
      expect(rel(result.unselected), {'lib/other.dart'});
      // Listed even though it doesn't match the include glob: references can
      // live anywhere.
      expect(rel(result.generated), {'lib/model.g.dart'});
    },
  );

  test(
    'with includeGenerated, generated files are selected and none is listed as generated',
    () {
      write('lib/model.dart', 'class Model {}');
      write('lib/model.g.dart', '// generated\nclass ModelGen {}');

      final result = dartFilesByPath(
        .new(rootPath: tempDir.path, includeGenerated: true),
      );

      expect(rel(result.selected), {'lib/model.dart', 'lib/model.g.dart'});
      expect(result.generated, isEmpty);
    },
  );

  test(
    'a file matching additionalGeneratedGlobs is listed as generated, unlike an excluded one, which is unselected',
    () {
      write('lib/model.dart', 'class Model {}');
      write('lib/l10n/l10n.dart', 'abstract class AppLocalizations {}');
      write('lib/l10n/l10n_pl.dart', 'class AppLocalizationsPl {}');
      // Its name ends like a gen-l10n file's, but it is hand-written.
      write('lib/src/status_l10n.dart', 'String status() => "";');

      final result = dartFilesByPath(
        .new(
          rootPath: tempDir.path,
          additionalGeneratedGlobs: const ['lib/l10n/**'],
        ),
      );
      expect(rel(result.selected), {
        'lib/model.dart',
        'lib/src/status_l10n.dart',
      });
      expect(rel(result.generated), {
        'lib/l10n/l10n.dart',
        'lib/l10n/l10n_pl.dart',
      });

      final excluded = dartFilesByPath(
        .new(rootPath: tempDir.path, excludeGlobs: const ['lib/l10n/**']),
      );
      expect(rel(excluded.selected), {
        'lib/model.dart',
        'lib/src/status_l10n.dart',
      });
      expect(rel(excluded.unselected), {
        'lib/l10n/l10n.dart',
        'lib/l10n/l10n_pl.dart',
      });
      expect(excluded.generated, isEmpty);

      // --generated scans them like any other file.
      final scanned = dartFilesByPath(
        .new(
          rootPath: tempDir.path,
          includeGenerated: true,
          additionalGeneratedGlobs: const ['lib/l10n/**'],
        ),
      );
      expect(scanned.selected, hasLength(4));
      expect(scanned.generated, isEmpty);
    },
  );

  test('generated files inside skipped dirs are in no list', () {
    write('lib/model.dart', 'class Model {}');
    write('build/gen.g.dart', '// generated\nclass Gen {}');
    write('.dart_tool/tool.g.dart', '// generated\nclass Tool {}');

    final result = dartFilesByPath(.new(rootPath: tempDir.path));

    expect(rel(result.selected), {'lib/model.dart'});
    expect(result.unselected, isEmpty);
    expect(result.generated, isEmpty);
  });

  test('files in `.widget_preview` are in no list', () {
    write('lib/button.dart', 'class Button {}');
    write('.widget_preview/lib/main.dart', 'void main() {}');

    final result = dartFilesByPath(.new(rootPath: tempDir.path));

    expect(rel(result.selected), {'lib/button.dart'});
    expect(result.unselected, isEmpty);
    expect(result.generated, isEmpty);
  });
}
