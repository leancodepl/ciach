import 'dart:io';

import 'package:ciach/src/analysis/dart_text.dart';
import 'package:ciach/src/analysis/discovered_files.dart';
import 'package:path/path.dart' as p;
import 'package:test/test.dart';

void main() {
  late Directory tempDir;

  setUp(() {
    tempDir = .systemTemp.createTempSync('ciach_discovery_test_');
  });

  tearDown(() {
    tempDir.deleteSync(recursive: true);
  });

  void write(String relativePath, String content) {
    File(p.join(tempDir.path, p.joinAll(p.posix.split(relativePath))))
      ..createSync(recursive: true)
      ..writeAsStringSync(content);
  }

  /// Whether [source] starts with a banner that marks generated code.
  bool bannerIn(String source) =>
      isGeneratedBanner(source, parseDart(source).unit);

  /// Relative POSIX paths of [absolutePaths], for order-independent asserts.
  Set<String> rel(List<String> absolutePaths) => {
    for (final path in absolutePaths)
      p.split(p.relative(path, from: tempDir.path)).join('/'),
  };

  test(
    'excludes generated files from candidates but keeps them for their references',
    () {
      write('lib/model.dart', 'class Model {}');
      write('lib/model.g.dart', '// generated\nclass ModelGen {}');
      write(
        'lib/mapper.dart',
        '// GENERATED CODE - DO NOT MODIFY BY HAND\nclass Mapper {}',
      );

      final result = discoverDartFiles(.new(rootPath: tempDir.path));

      // The `.g.dart` and banner-marked files are excluded from candidates…
      expect(rel(result.candidates), {'lib/model.dart'});
      // …but still returned for their references.
      expect(rel(result.referenceOnly), {
        'lib/model.g.dart',
        'lib/mapper.dart',
      });
    },
  );

  test(
    'a file with a banner is reference-only also when the globs leave it out',
    () {
      write('lib/model.dart', 'class Model {}');
      write(
        'lib/gen/mapper.dart',
        '// GENERATED CODE - DO NOT MODIFY BY HAND\n',
      );
      write('lib/gen/other.dart', 'class Other {}');

      final result = discoverDartFiles(
        .new(rootPath: tempDir.path, excludeGlobs: const ['lib/gen/**']),
      );

      expect(rel(result.candidates), {'lib/model.dart'});
      expect(rel(result.referenceOnly), {'lib/gen/mapper.dart'});
    },
  );

  test(
    'with includeGenerated, a file with a banner is a candidate when the globs select it',
    () {
      write('lib/mapper.dart', '// GENERATED CODE - DO NOT MODIFY BY HAND\n');
      write('test/mapper.dart', '// GENERATED CODE - DO NOT MODIFY BY HAND\n');

      final result = discoverDartFiles(
        .new(
          rootPath: tempDir.path,
          includeGenerated: true,
          includeGlobs: const ['lib/**'],
        ),
      );

      expect(rel(result.candidates), {'lib/mapper.dart'});
      expect(result.referenceOnly, isEmpty);
    },
  );

  test('a file marked ciach:ignore-file is opened but not scanned', () {
    write('lib/model.dart', 'class Model {}');
    write('lib/catalog.dart', '''
// ciach:ignore-file
class Catalog {}
''');
    write('lib/excluded.dart', '''
// ciach:ignore-file
class Excluded {}
''');

    final result = discoverDartFiles(
      .new(rootPath: tempDir.path, excludeGlobs: const ['lib/excluded.dart']),
    );

    expect(rel(result.candidates), {'lib/model.dart'});
    expect(rel(result.referenceOnly), {'lib/catalog.dart'});
    expect(rel(result.ignored), {'lib/catalog.dart'});
  });

  test('a file that `flutterfire configure` wrote is generated', () {
    write('lib/model.dart', 'class Model {}');
    write('lib/firebase_options_prod.dart', '''
// File generated by FlutterFire CLI.
// ignore_for_file: type=lint
class DefaultFirebaseOptions {}
''');

    final result = discoverDartFiles(.new(rootPath: tempDir.path));

    expect(rel(result.candidates), {'lib/model.dart'});
    expect(rel(result.referenceOnly), {'lib/firebase_options_prod.dart'});
  });

  group('isGeneratedBanner', () {
    test('recognizes how each generator words it', () {
      for (final banner in [
        '// GENERATED CODE - DO NOT MODIFY BY HAND\n',
        '''
// dart format width=80
// coverage:ignore-file
// GENERATED CODE - DO NOT MODIFY BY HAND
''',
        '''
//
//  Generated code. Do not modify.
//  source: a.proto
''',
        '// This is a generated file - do not edit.\n',
        '/* AUTOMATICALLY GENERATED CODE DO NOT MODIFY */\n/*   To generate run: "serverpod generate"    */\n',
        '// Autogenerated from Pigeon (v22.4.0), do not edit directly.\n',
        '// AUTO GENERATED FILE, DO NOT EDIT.\n',
        '''
// Mocks generated by Mockito 5.4.4 from annotations
// in app/test/a_test.dart.
// Do not manually edit this file.
''',
        '''
/*
 * This file is automatically generated,
 * so please do not edit it.
 */
''',
        '// Code generated by tool. DO NOT EDIT.\n',
      ]) {
        expect(bannerIn('${banner}class A {}\n'), isTrue, reason: banner);
      }
    });

    test('reads only the leading non-doc comments', () {
      for (final source in [
        'class A {}\n// GENERATED CODE. DO NOT EDIT.\n',
        '/// Do not edit the generated files under lib/gen.\nlibrary;\n',
        '// Copyright 2026. Do not redistribute.\nclass A {}\n',
        "const s = 'Generated code. Do not modify.';\n",
        '// Generated files go to lib/gen.\nclass A {}\n',
      ]) {
        expect(bannerIn(source), isFalse, reason: source);
      }
    });
  });
}
