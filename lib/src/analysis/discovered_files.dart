/// The `.dart` files that a run scans, and those that it only reads for their
/// references: sorted by their paths, then by what their comments say.
library;

import 'dart:math';

import 'package:analyzer/dart/ast/ast.dart';
import 'package:ciach/src/analysis/comments.dart';
import 'package:ciach/src/analysis/dart_text.dart';
import 'package:ciach/src/model/finder_options.dart';
import 'package:ciach/src/source/ignore_markers.dart';
import 'package:ciach/src/workspace/file_discovery.dart';
import 'package:ciach/src/workspace/packages.dart';
import 'package:collection/collection.dart';

/// The `.dart` files discovered under the configured root, split by role.
typedef DiscoveredDartFiles = ({
  /// Files whose declarations are scanned and reported as candidates.
  List<String> candidates,

  /// Generated files excluded from [candidates] whose references still
  /// count, so a declaration referenced *only* from generated code isn't
  /// misreported as unused. Files marked `// ciach:ignore-file` are among
  /// them, even when generated files are candidates.
  List<String> referenceOnly,

  /// The files of [referenceOnly] that a `// ciach:ignore-file` marker put there.
  List<String> ignored,
});

/// Discovers the `.dart` files under the configured root that should be
/// scanned for declarations, honoring include/exclude globs and
/// generated-file rules, and the excluded generated files as `referenceOnly`
/// (see [DiscoveredDartFiles]), so that the caller can resolve the references
/// in them.
///
/// Results are returned as absolute file paths, sorted for stable output.
/// The reference-only set is deliberately not filtered by include/exclude
/// globs — a reference can live in a generated file the user isn't scanning —
/// though skipped directories (`build/`, `.dart_tool/`, …) are still excluded.
DiscoveredDartFiles discoverDartFiles(FinderOptions options) {
  final byPath = dartFilesByPath(options);
  final readsBanner = !options.includeGenerated;
  final roles = {
    for (final path in byPath.selected)
      path: _roleOf(path, selected: true, readsBanner: readsBanner),
    // A file that the globs leave out matters only when a banner makes it
    // reference-only.
    if (readsBanner)
      for (final path in byPath.unselected)
        path: _roleOf(path, selected: false, readsBanner: true),
  };
  List<String> withRole(_Role role) => [
    for (final MapEntry(key: path, value: found) in roles.entries)
      if (found == role) path,
  ];
  final ignored = withRole(.ignored);
  return (
    candidates: withRole(.candidate),
    referenceOnly: [
      ...byPath.generated,
      ...withRole(.generated),
      ...ignored,
    ].sorted(),
    ignored: ignored,
  );
}

/// What a discovered file is to a run.
enum _Role { candidate, generated, ignored, skipped }

/// The role of the file at [path], which the globs select when [selected]:
/// generated when [readsBanner] and its banner says so, ignored when a
/// `// ciach:ignore-file` marker says so, and otherwise a candidate when
/// [selected].
_Role _roleOf(
  String path, {
  required bool selected,
  required bool readsBanner,
}) {
  final content = readSource(path) ?? '';
  final unit = parseDart(content).unit;
  if (readsBanner && isGeneratedBanner(content, unit)) {
    return .generated;
  }
  if (!selected) {
    return .skipped;
  }
  return IgnoreMarkers.parse(content, lineCommentsOf(unit)).ignoresFile
      ? .ignored
      : .candidate;
}

/// The banner that build_runner writes at the top of a generated file. It is
/// matched anywhere in the first 300 characters of the file.
const _buildBanner = 'GENERATED CODE - DO NOT MODIFY BY HAND';

/// A banner that warns against editing generated code, or `flutterfire
/// configure`'s, which doesn't. `.` also matches a line break, which a
/// `/* */` banner can have between its words.
final _banner = RegExp(
  r'\b(?:auto-?)?generated\b.{0,200}?\b(?:do not|don.t|must not)\s+(?:\w+\s+)?(?:edit|modify)\b|\b(?:do not|don.t)\s+(?:edit|modify)\b.{0,200}?\bgenerated\b|\bgenerated by flutterfire cli\b',
  caseSensitive: false,
  dotAll: true,
);

/// Returns whether the file with [content], which parses to [unit], starts
/// with a banner that marks generated code. Only the comments before its
/// first token are read. Doc comments are skipped, because a doc comment can
/// mention generated code in a file that is not generated.
bool isGeneratedBanner(String content, CompilationUnit unit) =>
    content.substring(0, min(content.length, 300)).contains(_buildBanner) ||
    _banner.hasMatch(
      commentsBefore(unit.beginToken)
          .map((comment) => comment.lexeme)
          .whereNot((text) => text.startsWith('///'))
          .join(' '),
    );
